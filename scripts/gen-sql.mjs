// Regenerates lib/setup-sql.ts (used by the /setup page) and lib/demo-sql.ts (used by the demo's refresh button)
// from the SQL files in db/. Run it after changing a migration, db/seed.sql or db/demo.sql: npm run gen:sql
import { readFileSync, writeFileSync } from "node:fs";
const read = (f) => readFileSync(new URL(`../${f}`, import.meta.url), "utf8");
writeFileSync(new URL("../lib/setup-sql.ts", import.meta.url),
  `// Generated by scripts/gen-sql.mjs from db/migrations/0001_baseline.sql and db/seed.sql, so the /setup page can create the database without a terminal.\nexport const schemaSql = ${JSON.stringify(read("db/migrations/0001_baseline.sql"))};\nexport const seedSql = ${JSON.stringify(read("db/seed.sql"))};\n`);
writeFileSync(new URL("../lib/demo-sql.ts", import.meta.url),
  `// Generated by scripts/gen-sql.mjs from db/demo.sql.\nexport const demoSql = ${JSON.stringify(read("db/demo.sql"))};\n`);
console.log("generated lib/setup-sql.ts and lib/demo-sql.ts");
